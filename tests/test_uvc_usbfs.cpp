void testInfo() {
    evo::uvc::Info info;
    CHECK(evo::uvc::parseInfo(kEasyCap, sizeof(kEasyCap), &info));
    CHECK(info.bcdUvc == 0x0100);
    CHECK(info.vsInterface == 1);
    CHECK(info.altSetting == 1);
    CHECK(info.endpoint == 0x83);
    CHECK(info.packetSize == 3072);  // 1024 x 3 transactions
    CHECK(info.mjpegFormat == 1);
    CHECK(info.frameCount == 3);
    CHECK(info.frames[0][0] == 480 && info.frames[0][1] == 320);
    CHECK(info.frames[1][0] == 640 && info.frames[1][1] == 480);
    CHECK(info.frames[2][0] == 720 && info.frames[2][1] == 480);
    evo::uvc::Info none;
    CHECK(!evo::uvc::parseInfo(kEasyCap, 18, &none));  // the device descriptor alone
    unsigned char broken[sizeof(kEasyCap)];
    memcpy(broken, kEasyCap, sizeof(kEasyCap));
    broken[18] = 0;  // a zero length stops the walk: nothing past it is read
    CHECK(!evo::uvc::parseInfo(broken, sizeof(broken), &none));
}

// One isochronous packet: the 2-byte UVC header (FID, EOF, error bits) and its data.
unsigned packet(unsigned char* out, int fid, bool eof, bool error, const char* data) {
    out[0] = 2;
    out[1] = static_cast<unsigned char>(0x80 | (fid & 1) | (eof ? 2 : 0) | (error ? 0x40 : 0));
    const size_t n = strlen(data);
    memcpy(out + 2, data, n);
    return static_cast<unsigned>(n + 2);
}

void testAssembler() {
    unsigned char buf[64];
    evo::uvc::Assembler a(buf, sizeof(buf));
    unsigned char p[64];
    // the first frame seen may have started before: dropped, even with its EOF
    CHECK(!a.feed(p, packet(p, 0, false, false, "\xff\xd8xx")));
    CHECK(!a.feed(p, packet(p, 0, true, false, "yy")));
    // the next one, in two packets, ends with EOF: a JPEG
    CHECK(!a.feed(p, packet(p, 1, false, false,
                            "\xff\xd8"
                            "AB")));
    CHECK(a.feed(p, packet(p, 1, true, false, "CD")));
    CHECK(a.size() == 6 && !memcmp(a.frame(),
                                   "\xff\xd8"
                                   "ABCD",
                                   6));
    CHECK(a.frames() == 1);
    // a frame that is not a JPEG completes but is not given
    CHECK(!a.feed(p, packet(p, 0, false, false, "notjpeg")));
    CHECK(!a.feed(p, packet(p, 0, true, true, "!")));
    CHECK(a.frames() == 2 && a.errors() == 1);
    // a frame without EOF is counted when the FID flips, the next one is assembled
    CHECK(!a.feed(p, packet(p, 1, false, false,
                            "\xff\xd8"
                            "1")));
    CHECK(!a.feed(p, packet(p, 0, false, false,
                            "\xff\xd8"
                            "2")));
    CHECK(a.frames() == 3);
    CHECK(a.feed(p, packet(p, 0, true, false, "3")));
    CHECK(a.size() == 4 && !memcmp(a.frame(),
                                   "\xff\xd8"
                                   "23",
                                   4));
    // malformed headers are ignored
    unsigned char bad[4] = {9, 0x83, 0, 0};
    CHECK(!a.feed(bad, 4));
    CHECK(!a.feed(bad, 1));
    // more than the buffer holds: the rest is dropped, never written past it
    evo::uvc::Assembler small(buf, 8);
    CHECK(!small.feed(p, packet(p, 0, false, false, "x")));
    CHECK(!small.feed(p, packet(p, 1, false, false,
                                "\xff\xd8"
                                "123")));
    CHECK(!small.feed(p, packet(p, 1, false, false, "4567890")));  // would pass 8 bytes: dropped
    CHECK(small.feed(p, packet(p, 1, true, false, "ab")));
    CHECK(small.size() == 7 && !memcmp(small.frame(),
                                       "\xff\xd8"
                                       "123ab",
                                       7));
}

void writeFile(const char* path, const char* text) {
    FILE* f = fopen(path, "w");
    if (f) {
        fputs(text, f);
        fclose(f);
    }
}

void device(const char* root, const char* name, const char* vendor, const char* product) {
    char path[512];
    snprintf(path, sizeof(path), "%s/%s", root, name);
    mkdir(path, 0755);
    snprintf(path, sizeof(path), "%s/%s/idVendor", root, name);
    writeFile(path, vendor);
    snprintf(path, sizeof(path), "%s/%s/idProduct", root, name);
    writeFile(path, product);
}

void testFind() {
    char root[] = "/tmp/uvc-usbfs-test-XXXXXX";
    CHECK(mkdtemp(root) != nullptr);
    char port[32] = "";
    CHECK(!evo::uvc::findDevice(0x534d, 0x0021, port, sizeof(port), root));
    device(root, "usb3", "534d\n", "0021\n");     // a root hub's name: skipped
    device(root, "3-1:1.0", "534d\n", "0021\n");  // an interface: skipped
    device(root, "1-1", "18d1\n", "2d00\n");      // a phone in accessory mode
    CHECK(!evo::uvc::findDevice(0x534d, 0x0021, port, sizeof(port), root));
    device(root, "3-1", "534d\n", "0021\n");
    CHECK(evo::uvc::findDevice(0x534d, 0x0021, port, sizeof(port), root));
    CHECK(!strcmp(port, "3-1"));
    char tiny[3];
    CHECK(!evo::uvc::findDevice(0x534d, 0x0021, tiny, sizeof(tiny), root));  // "3-1" does not fit: not returned
    CHECK(!evo::uvc::findDevice(0x534d, 0x0022, port, sizeof(port), root));
    char cmd[600];
    snprintf(cmd, sizeof(cmd), "rm -rf '%s'", root);
    CHECK(system(cmd) == 0);
}

